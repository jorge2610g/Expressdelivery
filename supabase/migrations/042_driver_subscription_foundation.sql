
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
grant usage on schema private to service_role;

create table if not exists public.driver_subscription_plans (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  amount numeric(12,2) not null check (amount >= 0),
  days integer not null check (days > 0),
  currency_code text not null default 'BOB',
  benefits jsonb not null default '[]'::jsonb check (jsonb_typeof(benefits)='array'),
  active boolean not null default true,
  sort_order integer not null default 0,
  zone_key text not null default 'trinidad',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.driver_subscription_settings (
  id boolean primary key default true check (id),
  enabled boolean not null default true,
  enforce_access boolean not null default false,
  provider text not null default 'veripagos',
  provider_enabled boolean not null default false,
  qr_validity text not null default '0/00:15',
  zone_key text not null default 'trinidad',
  updated_at timestamptz not null default now(),
  updated_by uuid
);

insert into public.driver_subscription_settings(id) values(true)
on conflict(id) do nothing;


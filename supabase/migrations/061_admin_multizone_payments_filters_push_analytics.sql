-- Admin multizone payments, server-side filters, push analytics and partner settlements.
-- Additive/backward-compatible migration: existing service_zones.payment_provider and legacy RPCs stay intact.

alter table public.service_zones
  add column if not exists region_department text;

create table if not exists public.payment_method_catalog (
  provider_key text primary key,
  display_name text not null,
  provider_type text not null default 'gateway'
    check (provider_type in ('gateway','cash','transfer','wallet','card','other')),
  active boolean not null default true,
  credential_scope text not null default 'zone'
    check (credential_scope in ('zone','global','none')),
  supports_rides boolean not null default true,
  supports_delivery boolean not null default true,
  supports_subscriptions boolean not null default false,
  supports_wallet boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.payment_method_catalog enable row level security;

create table if not exists public.zone_payment_methods (
  id bigint generated by default as identity primary key,
  zone_id uuid not null references public.service_zones(id) on delete cascade,
  provider_key text not null references public.payment_method_catalog(provider_key) on update cascade,
  enabled boolean not null default true,
  use_rides boolean not null default true,
  use_delivery boolean not null default true,
  use_subscriptions boolean not null default false,
  use_wallet boolean not null default false,
  is_primary boolean not null default false,
  sort_order integer not null default 100,
  public_config jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(zone_id, provider_key)
);

alter table public.zone_payment_methods enable row level security;


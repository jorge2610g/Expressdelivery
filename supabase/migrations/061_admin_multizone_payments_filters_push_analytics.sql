create or replace function public.admin_payment_overview_v2(
  p_from timestamptz default null,
  p_to timestamptz default null,
  p_zone_id uuid default null,
  p_limit integer default 100,
  p_offset integer default 0
)
returns jsonb
language plpgsql
stable
security definer
set search_path='public'
as $$
begin
  if not public.is_admin() then raise exception 'No autorizado'; end if;
  return jsonb_build_object(
    'summary',jsonb_build_object(
      'paid_count',(
        select count(*)
        from public.payment_transactions p
        left join public.trips t on t.id=p.trip_id
        left join public.ride_requests rr on rr.id=t.ride_request_id
        left join public.users payer on payer.id=p.payer_id
        where p.status='paid'
          and (p_from is null or coalesce(p.paid_at,p.created_at)>=p_from)
          and (p_to is null or coalesce(p.paid_at,p.created_at)<p_to)
          and (p_zone_id is null or coalesce(rr.zone_id,payer.last_zone_id)=p_zone_id)
      ),
      'pending_count',(
        select count(*)
        from public.payment_transactions p
        left join public.trips t on t.id=p.trip_id
        left join public.ride_requests rr on rr.id=t.ride_request_id
        left join public.users payer on payer.id=p.payer_id

create or replace function public.admin_upsert_zone_payment_method(
  p_zone_id uuid,
  p_provider_key text,
  p_enabled boolean default true,
  p_use_rides boolean default true,
  p_use_delivery boolean default true,
  p_use_subscriptions boolean default false,
  p_use_wallet boolean default false,
  p_is_primary boolean default false,
  p_sort_order integer default 100
)
returns bigint
language plpgsql
security definer
set search_path='public'
as $$
declare
  v_id bigint;
  v_provider text := lower(trim(coalesce(p_provider_key,'')));
begin
  if not public.is_admin() then raise exception 'No autorizado'; end if;
  if not exists(select 1 from public.service_zones where id=p_zone_id) then
    raise exception 'Zona inválida';
  end if;
  if not exists(select 1 from public.payment_method_catalog where provider_key=v_provider and active=true) then
    raise exception 'Método de pago inválido o inactivo';
  end if;

  if coalesce(p_is_primary,false) then
    update public.zone_payment_methods set is_primary=false,updated_at=now()
    where zone_id=p_zone_id and is_primary=true;
  end if;

  insert into public.zone_payment_methods(
    zone_id,provider_key,enabled,use_rides,use_delivery,use_subscriptions,use_wallet,is_primary,sort_order
  )
  values(
    p_zone_id,v_provider,coalesce(p_enabled,true),coalesce(p_use_rides,true),
    coalesce(p_use_delivery,true),coalesce(p_use_subscriptions,false),
    coalesce(p_use_wallet,false),coalesce(p_is_primary,false),coalesce(p_sort_order,100)
  )
  on conflict(zone_id,provider_key) do update set
    enabled=excluded.enabled,
    use_rides=excluded.use_rides,
    use_delivery=excluded.use_delivery,
    use_subscriptions=excluded.use_subscriptions,
    use_wallet=excluded.use_wallet,
    is_primary=excluded.is_primary,
    sort_order=excluded.sort_order,
    updated_at=now()
  returning id into v_id;

  -- Legacy mirror keeps the currently published mobile app compatible.
  if coalesce(p_is_primary,false) then
    update public.service_zones
    set payment_provider=v_provider,
        payment_enabled=coalesce(p_enabled,true),
        updated_at=now()
    where id=p_zone_id;
  end if;

  perform public.admin_log_action(
    'upsert_zone_payment_method','service_zones',p_zone_id::text,
    jsonb_build_object(
      'provider_key',v_provider,'enabled',p_enabled,'rides',p_use_rides,
      'delivery',p_use_delivery,'subscriptions',p_use_subscriptions,
      'wallet',p_use_wallet,'primary',p_is_primary
    )
  );
  return v_id;
end;
$$;

create or replace function public.admin_delete_zone_payment_method(
  p_zone_id uuid,
  p_provider_key text
)
returns boolean
language plpgsql
security definer
set search_path='public'
as $$
declare
  v_was_primary boolean := false;
begin
  if not public.is_admin() then raise exception 'No autorizado'; end if;
  select is_primary into v_was_primary
  from public.zone_payment_methods
  where zone_id=p_zone_id and provider_key=lower(trim(p_provider_key));

  delete from public.zone_payment_methods
  where zone_id=p_zone_id and provider_key=lower(trim(p_provider_key));

  if v_was_primary then
    update public.service_zones
    set payment_provider=null,payment_enabled=false,updated_at=now()
    where id=p_zone_id;
  end if;
  return found;
end;
$$;

create or replace function public.admin_upsert_zone_v2(
  p_id uuid,
  p_name text,
  p_city text,
  p_region_department text,
  p_country text,
  p_active boolean,
  p_center_latitude numeric,
  p_center_longitude numeric,
  p_radius_km numeric,
  p_zone_key text,
  p_currency_code text
)
returns uuid
language plpgsql
security definer
set search_path='public'
as $$
declare
  v_id uuid;
  v_key text;
begin
  if not public.is_admin() then raise exception 'No autorizado'; end if;
  if trim(coalesce(p_name,''))='' then raise exception 'Nombre requerido'; end if;
  if p_radius_km is null or p_radius_km<=0 then raise exception 'Radio inválido'; end if;

  v_key := lower(trim(coalesce(p_zone_key,'')));
  if v_key='' then
    v_key := lower(regexp_replace(
      translate(coalesce(nullif(trim(p_city),''),trim(p_name)),
      'ÁÉÍÓÚÜÑáéíóúüñ','AEIOUUNaeiouun'),
      '[^a-zA-Z0-9]+','_','g'
    ));
  end if;
  v_key := trim(both '_' from v_key);
  if v_key !~ '^[a-z0-9_]{2,60}$' then raise exception 'Clave de zona inválida'; end if;

  if p_id is null then
    insert into public.service_zones(
      name,city,region_department,country,active,center_latitude,center_longitude,
      radius_km,zone_key,currency_code
    )
    values(
      trim(p_name),nullif(trim(coalesce(p_city,'')),''),
      nullif(trim(coalesce(p_region_department,'')),''),
      coalesce(nullif(trim(coalesce(p_country,'')),''),'Bolivia'),
      coalesce(p_active,true),p_center_latitude,p_center_longitude,p_radius_km,
      v_key,upper(coalesce(nullif(trim(p_currency_code),''),'BOB'))
    )
    returning id into v_id;
  else
    update public.service_zones
    set name=trim(p_name),
        city=nullif(trim(coalesce(p_city,'')),''),
        region_department=nullif(trim(coalesce(p_region_department,'')),''),
        country=coalesce(nullif(trim(coalesce(p_country,'')),''),country),
        active=coalesce(p_active,true),
        center_latitude=p_center_latitude,
        center_longitude=p_center_longitude,
        radius_km=p_radius_km,
        zone_key=v_key,
        currency_code=upper(coalesce(nullif(trim(p_currency_code),''),currency_code)),
        updated_at=now()
    where id=p_id
    returning id into v_id;
  end if;
  if v_id is null then raise exception 'Zona no encontrada'; end if;
  return v_id;
end;
$$;


create or replace function public.zone_payment_methods_for_context(
  p_zone_id uuid,
  p_context text
)
returns jsonb
language plpgsql
stable
security definer
set search_path='public'
as $$
declare
  v_context text := lower(trim(coalesce(p_context,'rides')));
begin
  if auth.uid() is null then raise exception 'Autenticación requerida'; end if;
  if v_context not in ('rides','delivery','subscriptions','wallet') then
    raise exception 'Contexto inválido';
  end if;
  return (
    select coalesce(jsonb_agg(
      jsonb_build_object(
        'provider_key',m.provider_key,
        'display_name',c.display_name,
        'provider_type',c.provider_type,
        'is_primary',m.is_primary,
        'sort_order',m.sort_order,
        'public_config',m.public_config
      )
      order by m.is_primary desc,m.sort_order,c.display_name
    ),'[]'::jsonb)
    from public.zone_payment_methods m
    join public.payment_method_catalog c on c.provider_key=m.provider_key
    where m.zone_id=p_zone_id
      and m.enabled=true and c.active=true
      and case v_context
        when 'rides' then m.use_rides
        when 'delivery' then m.use_delivery
        when 'subscriptions' then m.use_subscriptions
        when 'wallet' then m.use_wallet
      end
  );
end;
$$;

create or replace function public.admin_trip_list_v2(
  p_from timestamptz default null,
  p_to timestamptz default null,
  p_zone_id uuid default null,
  p_status text default null,
  p_limit integer default 100,
  p_offset integer default 0
)
returns jsonb
language plpgsql
stable
security definer
set search_path='public'
as $$
begin
  if not public.is_admin() then raise exception 'No autorizado'; end if;
  return (
    select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at desc),'[]'::jsonb)
    from (
      select
        t.id,t.status,t.final_fare,t.payment_status,t.created_at,t.completed_at,
        pu.full_name as passenger_name,du.full_name as driver_name,
        rr.pickup_address,rr.destination_address,rr.category,rr.currency,rr.payment_method,
        rr.zone_id,z.name as zone_name,z.city,z.region_department,z.country
      from public.trips t
      left join public.ride_requests rr on rr.id=t.ride_request_id
      left join public.users pu on pu.id=t.passenger_id
      left join public.users du on du.id=t.driver_id
      left join public.service_zones z on z.id=rr.zone_id
      where (p_from is null or t.created_at>=p_from)
        and (p_to is null or t.created_at<p_to)
        and (p_zone_id is null or rr.zone_id=p_zone_id)
        and (p_status is null or p_status='' or t.status=p_status)
      order by t.created_at desc
      limit greatest(1,least(coalesce(p_limit,100),500))
      offset greatest(0,coalesce(p_offset,0))
    ) x
  );
end;
$$;


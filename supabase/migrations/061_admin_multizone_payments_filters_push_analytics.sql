          and (p_zone_id is null or coalesce(rr.zone_id,payer.last_zone_id)=p_zone_id)
      ),
      'totals_by_currency',(
        select coalesce(jsonb_object_agg(currency,total),'{}'::jsonb)
        from (
          select p.currency,sum(p.amount)::numeric as total
          from public.payment_transactions p
          left join public.trips t on t.id=p.trip_id
          left join public.ride_requests rr on rr.id=t.ride_request_id

            and (p_zone_id is null or coalesce(rr.zone_id,payer.last_zone_id)=p_zone_id)
          group by p.currency
        ) sums
      ),
      'pending_by_currency',(
        select coalesce(jsonb_object_agg(currency,total),'{}'::jsonb)
        from (
          select p.currency,sum(p.amount)::numeric as total
          from public.payment_transactions p
          left join public.trips t on t.id=p.trip_id
          left join public.ride_requests rr on rr.id=t.ride_request_id
          left join public.users payer on payer.id=p.payer_id
          where p.status='pending'
            and (p_from is null or p.created_at>=p_from)
            and (p_to is null or p.created_at<p_to)
            and (p_zone_id is null or coalesce(rr.zone_id,payer.last_zone_id)=p_zone_id)
          group by p.currency
        ) sums
      )
    ),
    'recent',(
      select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at desc),'[]'::jsonb)
      from (
        select p.id,p.amount,p.currency,p.method,p.provider,p.status,p.created_at,p.paid_at,
               pu.full_name as payer_name,ru.full_name as payee_name,
               p.trip_id,p.delivery_id,
               coalesce(rr.zone_id,pu.last_zone_id) as zone_id,
               z.name as zone_name
        from public.payment_transactions p
        left join public.users pu on pu.id=p.payer_id
        left join public.users ru on ru.id=p.payee_id
        left join public.trips t on t.id=p.trip_id
        left join public.ride_requests rr on rr.id=t.ride_request_id
        left join public.service_zones z on z.id=coalesce(rr.zone_id,pu.last_zone_id)
        where (p_from is null or p.created_at>=p_from)
          and (p_to is null or p.created_at<p_to)
          and (p_zone_id is null or coalesce(rr.zone_id,pu.last_zone_id)=p_zone_id)
        order by p.created_at desc
        limit greatest(1,least(coalesce(p_limit,100),500))
        offset greatest(0,coalesce(p_offset,0))
      ) x
    )
  );
end;
$$;

